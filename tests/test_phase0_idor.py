@pytest.mark.db
async def test_data_routes_reject_a_missing_token(client):
    """Unauthenticated access to a data route must be refused, not defaulted."""
    for method, path in [
        ("GET", "/api/v1/transactions"),
        ("GET", "/api/v1/analysis/summary"),
        ("GET", "/api/v1/analysis/budget"),
        ("GET", "/api/v1/analysis/anomalies"),
        ("GET", "/api/v1/stats"),
        ("DELETE", "/api/v1/me"),
    ]:
        response = await client.request(method, path)
        assert response.status_code in (401, 403), (
            f"{method} {path} returned {response.status_code} with no token; " f"expected 401/403"
        )


@pytest.mark.db
async def test_alice_cannot_reach_bobs_data_through_any_route(client, alice, bob):
    """
    The end-to-end statement of the property.

    Alice holds a valid token. There is no parameter she can supply -- and no
    route she can call -- that returns Bob's rows, because her session is bound
    to her id and RLS filters on it.
    """
    import uuid as _uuid

    from tests.test_rls_isolation import seed_transaction

    await login(alice)

    # Give Bob a transaction that Alice must never see.
    marker = f"BOB-SECRET-{_uuid.uuid4().hex[:8]}"
    await seed_transaction(bob.user_id, marker)

    # Every attempt Alice could make to name Bob.
    attempts = [
        ("GET", f"/api/v1/transactions?user_id={bob.user_id}", None),
        ("GET", f"/api/v1/analysis/summary?user_id={bob.user_id}", None),
        ("GET", f"/api/v1/transactions/{bob.user_id}", None),
        ("GET", f"/api/v1/analyze/summary/{bob.user_id}", None),
        ("DELETE", f"/api/v1/user/{bob.user_id}", None),
        ("POST", "/api/v1/chat", {"query": "show my spending", "user_id": str(bob.user_id)}),
    ]

    for method, path, body in attempts:
        response = await client.request(method, path, json=body, headers=alice.auth_header)
        assert marker not in response.text, (
            f"{method} {path} leaked Bob's data to Alice " f"(status {response.status_code})"
        )
        # 404 (no such route), 422 (unexpected field rejected), 200 with only
        # Alice's own rows, or 404 "no transactions" are all acceptable. A 200
        # containing the marker is not, and is caught above.
        assert response.status_code != 500, (
            f"{method} {path} returned 500 -- an unhandled error is not a " f"security control"
        )
