"""
DEFINITION OF DONE #1 -- no endpoint accepts a user identifier from the URL.

The important property of this file is that it does not enumerate routes by
hand. A hand-written list proves only that the routes someone remembered to
list are safe; the route added next week is exactly the one that will be
vulnerable. So the tests below walk the **live OpenAPI document** generated by
the running application and fail on anything that looks like a user identifier,
wherever it appears.

Three surfaces are checked, because the original vulnerability appeared on all
three:

    POST   /analyze/budget/{user_id}      <- path parameter
    POST   /ingest?user_id=...            <- query parameter
    POST   /chat  {"user_id": "..."}      <- request body

and one behavioural check, because schema shape alone is not proof: Alice's
token must not be able to read Bob's data through any route at all.
"""

from __future__ import annotations

import re
from typing import Any, Dict, Iterator, List, Tuple

import pytest

from main import app
from tests.conftest import login

# A parameter is suspect if it names a *subject* the caller could substitute.
# Deliberately broad -- false positives here are cheap and force a deliberate
# decision, while a false negative is an IDOR shipped to production.
SUSPECT = re.compile(
    r"^(user|owner|account_holder|customer|subject|principal|member)"
    r"[_-]?(id|uuid|guid|ref|handle|identifier)$"
    r"|^(uid|userid|user)$",
    re.IGNORECASE,
)

# Routes served by the framework itself, not by this application.
EXEMPT_PATHS = {"/openapi.json", "/docs", "/redoc", "/docs/oauth2-redirect"}


def openapi() -> Dict[str, Any]:
    return app.openapi()


def iter_operations() -> Iterator[Tuple[str, str, Dict[str, Any]]]:
    for path, item in openapi().get("paths", {}).items():
        if path in EXEMPT_PATHS:
            continue
        for method, operation in item.items():
            if method.lower() in {"get", "post", "put", "patch", "delete"}:
                yield path, method.upper(), operation


def resolve(schema: Dict[str, Any], spec: Dict[str, Any]) -> Dict[str, Any]:
    """Follow a single ``$ref`` into ``components.schemas``."""
    ref = schema.get("$ref")
    if not ref or not ref.startswith("#/components/schemas/"):
        return schema
    name = ref.rsplit("/", 1)[-1]
    return spec.get("components", {}).get("schemas", {}).get(name, {})


def walk_properties(schema: Dict[str, Any], spec: Dict[str, Any], depth: int = 0) -> Iterator[str]:
    """Yield every property name reachable from a request-body schema."""
    if depth > 6 or not isinstance(schema, dict):
        return
    schema = resolve(schema, spec)

    for name, sub in (schema.get("properties") or {}).items():
        yield name
        yield from walk_properties(sub, spec, depth + 1)

    for key in ("items", "additionalProperties"):
        if isinstance(schema.get(key), dict):
            yield from walk_properties(schema[key], spec, depth + 1)

    for key in ("allOf", "anyOf", "oneOf"):
        for sub in schema.get(key) or []:
            yield from walk_properties(sub, spec, depth + 1)


