def test_no_path_or_query_parameter_names_a_user():
    """
    The original bug, stated as a test.

    ``POST /analyze/budget/{user_id}`` fails here on the path parameter;
    ``POST /ingest?user_id=`` fails on the query parameter.
    """
    offenders: List[str] = []
    for path, method, operation in iter_operations():
        for param in operation.get("parameters", []) or []:
            if SUSPECT.match(param.get("name", "")):
                offenders.append(
                    f"{method} {path} -> {param.get('in')} parameter " f"'{param.get('name')}'"
                )

    assert not offenders, (
        "User identifiers must come from the verified token, never the "
        "request. Offending parameters:\n  " + "\n  ".join(offenders)
    )


def test_no_request_body_carries_a_user_identifier():
    """``POST /chat {"user_id": ...}`` -- the third form of the same bug."""
    spec = openapi()
    offenders: List[str] = []

    for path, method, operation in iter_operations():
        body = operation.get("requestBody")
        if not body:
            continue
        for media_type, media in (body.get("content") or {}).items():
            schema = media.get("schema") or {}
            for prop in walk_properties(schema, spec):
                if SUSPECT.match(prop):
                    offenders.append(f"{method} {path} [{media_type}] -> '{prop}'")

    assert not offenders, (
        "Request bodies must not name their own subject. Offending "
        "properties:\n  " + "\n  ".join(offenders)
    )


def test_no_path_template_contains_an_identifier_segment():
    """
    Belt and braces.

    Catches ``/user/{id}`` and ``/users/{uuid}`` -- shapes where the parameter
    name alone ('id', 'uuid') would slip past a name-based filter but the
    surrounding path makes the subject unmistakable.
    """
    offenders: List[str] = []
    subject_words = {
        "user",
        "users",
        "customer",
        "customers",
        "member",
        "members",
        "account_holder",
        "profile",
        "profiles",
    }

    for path, method, _operation in iter_operations():
        segments = [s for s in path.split("/") if s]
        for i, seg in enumerate(segments):
            if seg.startswith("{") and i > 0 and segments[i - 1].lower() in subject_words:
                offenders.append(f"{method} {path} -> templated '{seg}' after '{segments[i-1]}'")

    assert not offenders, (
        "A templated segment directly under a subject collection is an IDOR "
        "by shape:\n  " + "\n  ".join(offenders)
    )


def test_every_data_route_declares_authentication():
    """
    Removing the parameter is not enough if the route is still anonymous.

    Only the routes listed as public may omit a security requirement; anything
    else must carry one, which FastAPI emits when the handler depends on the
    bearer scheme.
    """
    public = {
        ("/", "GET"),
        ("/health/live", "GET"),
        ("/health/ready", "GET"),
        ("/health/detailed", "GET"),
        ("/metrics", "GET"),
        ("/api/v1/health", "GET"),
        # Pre-authentication by definition.
        ("/api/v1/auth/register", "POST"),
        ("/api/v1/auth/login", "POST"),
        ("/api/v1/auth/refresh", "POST"),
        ("/api/v1/auth/mfa/verify", "POST"),
        # Called by the Account Aggregator, not by a user. Authenticated by
        # HMAC over the raw body instead of a bearer token -- see
        # test_aa_roundtrip.py::test_webhook_rejects_forged_signature.
        ("/api/v1/aa/webhooks/consent", "POST"),
        ("/api/v1/aa/webhooks/fi", "POST"),
        # /aa/sandbox/approve is deliberately NOT exempt: it stands in for the
        # user approving at their AA, and it requires a token like any other
        # route. Listing it here would have skipped the check.
        ("/api/v1/aa/info", "GET"),
    }

    unauthenticated: List[str] = []
    for path, method, operation in iter_operations():
        if (path, method) in public:
            continue
        if not operation.get("security"):
            unauthenticated.append(f"{method} {path}")

    assert (
        not unauthenticated
    ), "These routes serve or mutate user data without requiring a token:\n  " + "\n  ".join(
        unauthenticated
    )


def test_the_previously_vulnerable_routes_are_gone():
    """Named explicitly, so a regression is unmistakable in the failure output."""
    paths = set(openapi().get("paths", {}))
    for gone in [
        "/api/v1/analyze/budget/{user_id}",
        "/api/v1/analyze/summary/{user_id}",
        "/api/v1/analyze/forecast/{user_id}",
        "/api/v1/user/{user_id}",
        "/analyze/budget/{user_id}",
        "/analyze/summary/{user_id}",
        "/user/{user_id}",
    ]:
        assert gone not in paths, f"{gone} is still routed -- the IDOR is back"


